        rule("Punctuation", [
            "punctuation", "meta.brace", "delimiter", "punctuation.separator", "punctuation.terminator",
            "punctuation.accessor", "punctuation.definition.tag"], subtle),
        rule("Strings", ["string", "string.template", "attribute.value"], gold),
