def semantic(t) -> dict:
    P = t.colors
    return {
        "namespace": P["text"],
        "class": P["foam"],
        "interface": P["foam"],
        "enum": P["foam"],
        "struct": P["foam"],
        "type": P["foam"],
        "typeParameter": P["foam"],
        "parameter": P["iris"],
        "variable": P["text"],
        "variable.readonly": P["text"],
        "variable.defaultLibrary": {"foreground": P["rose"], "fontStyle": "italic"},
        "property": P["text"],
        "enumMember": P["gold"],
        "function": P["rose"],
        "method": P["rose"],
        "macro": P["iris"],
        "decorator": P["iris"],
        "selfKeyword": {"foreground": P["rose"], "fontStyle": "italic"},
        "*.deprecated": {"fontStyle": "strikethrough"},
    }


def theme_file(t) -> str:
    theme = {
        "$schema": "vscode://schemas/color-theme",
        "name": t.name,
        "type": t.variant,
        "semanticHighlighting": True,
        "colors": colors(t),
        "tokenColors": tokens(t),
        "semanticTokenColors": semantic(t),
    }
    return json.dumps(theme, indent=2, ensure_ascii=False) + "\n"


def build(themes) -> dict:
    return {f"themes/{t.slug}-color-theme.json": theme_file(t) for t in themes}
